import { ChromaClient } from "chromadb";
const [host, port] = process.argv.slice(2);
const client = new ChromaClient({ host, port: Number(port), ssl: false });
const out = {};
out.heartbeat = typeof (await client.heartbeat());
for (const c of await client.listCollections()) await client.deleteCollection({ name: c.name });
const col = await client.createCollection({ name: "js-docs", metadata: { lang: "js" }, embeddingFunction: null, configuration: { hnsw: { space: "cosine" } } });
await col.add({ ids: ["a", "b", "c"], embeddings: [[1, 0, 0], [0, 1, 0], [0.7, 0.7, 0]], documents: ["apple", "banana", "both"], metadatas: [{ k: 1 }, { k: 2 }, { k: 3, tags: ["x"] }] });
out.count = await col.count();
const q = await col.query({ queryEmbeddings: [[1, 0.1, 0]], nResults: 2, where: { k: { $gte: 1 } }, include: ["documents", "distances", "metadatas"] });
out.query = { ids: q.ids, docs: q.documents, dist: q.distances.map(r => r.map(d => Math.round(d * 1e5) / 1e5)) };
const g = await col.get({ where: { tags: { $contains: "x" } } });
out.get = g.ids;
await col.update({ ids: ["a"], metadatas: [{ k: 10 }] });
await col.upsert({ ids: ["d"], embeddings: [[0, 0, 1]], documents: ["dee"] });
out.afterWrites = (await col.get({ include: ["metadatas"] })).metadatas;
await col.delete({ ids: ["b"] });
out.final = (await col.get()).ids;
const again = await client.getCollection({ name: "js-docs", embeddingFunction: null });
out.meta = again.metadata;
console.log(JSON.stringify(out));
